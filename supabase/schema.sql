CREATE OR REPLACE FUNCTION public.update_user_subscription(
    p_user_id UUID,
    p_status TEXT,
    p_customer_id TEXT,
    p_subscription_id TEXT,
    p_next_billing TIMESTAMPTZ,
    p_event_occurred_at TIMESTAMPTZ
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF p_status IS NULL OR p_status NOT IN ('active', 'trialing', 'past_due', 'paused', 'canceled') THEN
        RAISE EXCEPTION 'Invalid subscription status';
    END IF;

    UPDATE profiles
    SET subscription_status = CASE
            WHEN p_status IN ('active', 'trialing') THEN 'active'
            WHEN p_status = 'past_due' THEN 'past_due'
            ELSE 'canceled'
        END,
        paddle_customer_id = p_customer_id,
        paddle_subscription_id = p_subscription_id,
        next_billing_date = p_next_billing,
        paddle_last_event_at = COALESCE(p_event_occurred_at, NOW()),
        updated_at = NOW()
    WHERE id = p_user_id
        AND (
            p_event_occurred_at IS NULL
            OR paddle_last_event_at IS NULL
            OR p_event_occurred_at >= paddle_last_event_at
        );

    IF NOT FOUND THEN
        IF EXISTS (SELECT 1 FROM profiles WHERE id = p_user_id) THEN
            RETURN;
        END IF;
        RAISE EXCEPTION 'Profile not found';
    END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.update_user_subscription(UUID, TEXT, TEXT, TEXT, TIMESTAMPTZ, TIMESTAMPTZ) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.update_user_subscription(UUID, TEXT, TEXT, TEXT, TIMESTAMPTZ, TIMESTAMPTZ) TO service_role;

CREATE OR REPLACE FUNCTION public.cancel_user_subscription(
    p_user_id UUID,
    p_event_occurred_at TIMESTAMPTZ
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    UPDATE profiles
    SET subscription_status = 'canceled',
        next_billing_date = NULL,
        paddle_last_event_at = COALESCE(p_event_occurred_at, NOW()),
        updated_at = NOW()
    WHERE id = p_user_id
        AND (
            p_event_occurred_at IS NULL
            OR paddle_last_event_at IS NULL
            OR p_event_occurred_at >= paddle_last_event_at
        );

    IF NOT FOUND THEN
        IF EXISTS (SELECT 1 FROM profiles WHERE id = p_user_id) THEN
            RETURN;
        END IF;
        RAISE EXCEPTION 'Profile not found';
    END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.cancel_user_subscription(UUID, TIMESTAMPTZ) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cancel_user_subscription(UUID, TIMESTAMPTZ) TO service_role;
